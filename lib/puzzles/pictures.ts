export function pictureGrid(p: Picture): number[][] {
  return p.rows.map((r) => [...r].map((ch) => (ch === "#" ? 1 : 0)));
}

export function picturePuzzle(p: Picture): NonogramPuzzle {
  return fromSolution(pictureGrid(p));
}
